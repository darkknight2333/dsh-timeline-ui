/**
 * Build dsh-timeline-ui.
 *
 * The harness loads a client plugin as `window.__ModuleLoader__.load({ id, factory })`, so the
 * source in src/client.js is written against that factory scope (it ends with `return { … }`).
 * This script wraps it, validates the result, and writes the two runtime files under lib/.
 *
 * No bundler and no dependencies: the output is deterministic for a given source + version.
 *
 *   node scripts/build.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

const source = fs.readFileSync(path.join(root, 'src', 'client.js'), 'utf8')

const problems = []
if (!/return\s*\{\s*\n\s*inject:/.test(source)) problems.push('src/client.js must end with `return { inject, apply }`')
if (/^\s*(import|export)\s/m.test(source)) problems.push('src/client.js must stay a plain factory body (no import/export)')
for (const [label, pattern] of [
  ['an absolute Windows path', /[A-Za-z]:\\\\/],
  ['a POSIX absolute path', /['"]\/(Users|home|opt|var)\//],
  ['a local link dependency', /link:/],
  ['a local package import', /(require|from)\s*\(?['"]@local\//],
  ['a profile name', /profiles[\\/]/],
  ['a personal user name', /[\\/]Users[\\/][^'"\s]+/],
]) {
  if (pattern.test(source)) problems.push('src/client.js still contains ' + label)
}

const banner = `/* ${pkg.name} v${pkg.version} — generated by scripts/build.mjs; edit src/client.js instead. */\n`
const client = `${banner}window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    'use strict'
    const React = require('react')
${source.trimEnd()}
  },
})
`

const host = fs.readFileSync(path.join(root, 'index.js'), 'utf8')

// Parse both artifacts without executing them.
try {
  // eslint-disable-next-line no-new-func
  new Function(client)
} catch (error) {
  problems.push('lib/client.js does not parse: ' + error.message)
}

if (problems.length > 0) {
  console.error('build failed:')
  for (const problem of problems) console.error('  - ' + problem)
  process.exit(1)
}

fs.mkdirSync(path.join(root, 'lib'), { recursive: true })
fs.writeFileSync(path.join(root, 'lib', 'client.js'), client)
fs.writeFileSync(path.join(root, 'lib', 'index.js'), host)

const kb = (text) => (Buffer.byteLength(text) / 1024).toFixed(1) + ' KB'
console.log('built ' + pkg.name + '@' + pkg.version)
console.log('  lib/client.js  ' + kb(client))
console.log('  lib/index.js   ' + kb(host))
